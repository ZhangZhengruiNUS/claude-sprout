import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const statePath = join(repoRoot, 'docs', 'handoff-state.json')
const outputPath = join(repoRoot, 'docs', 'next-session.md')

function run(command, args, fallback = 'unavailable') {
  try {
    return execFileSync(command, args, {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trim()
  } catch {
    return fallback
  }
}

function bulletList(items) {
  return items.map((item) => `- ${item}`).join('\n')
}

function numberedList(items) {
  return items.map((item, index) => `${index + 1}. ${item}`).join('\n')
}

function codeBlock(language, content) {
  return `\`\`\`${language}\n${content}\n\`\`\``
}

const state = JSON.parse(readFileSync(statePath, 'utf8'))
const now = new Intl.DateTimeFormat('sv-SE', {
  timeZone: 'Asia/Shanghai',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
  hour: '2-digit',
  minute: '2-digit',
  second: '2-digit',
  hour12: false,
}).format(new Date())

const remotes = run('git', ['remote', '-v'])
const packageJson = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'))
const scripts = Object.entries(packageJson.scripts ?? {})
  .map(([name, command]) => `- \`${name}\`: \`${command}\``)
  .join('\n')

const content = `# Next Session Handoff

Updated: ${now} Asia/Shanghai
Generated by: \`${state.updatedBy}\`

## Resume Protocol

When a new Codex session starts in this repository:

1. Read \`AGENTS.md\`.
2. Read this file.
3. Skim \`docs/devlog.md\`.
4. Run \`git status --short --branch\` and \`git log --oneline --decorate -5\` for live Git context.
5. If the user says "continue" or gives a new Agent Desktop Companion requirement, continue from "Next Tasks" unless newer user instructions override it.

## Git Context

This file intentionally does not embed \`git status\` or \`git log\` output.

Reason: \`docs/next-session.md\` is committed to the repository. Embedding the current commit hash makes the file self-referential, so a pre-commit-generated handoff is always one commit behind after the commit completes. Always use live command output for Git state.

Remotes:

${codeBlock('text', remotes)}

## Current State

${bulletList(state.currentState)}

## Implemented So Far

${bulletList(state.implemented)}

## Verification Commands

Known passing commands:

${codeBlock('powershell', state.knownPassingCommands.join('\n'))}

Package scripts:

${scripts}

Run the desktop exe:

${codeBlock('powershell', state.runCommands[0])}

Run the dev preview:

${codeBlock('powershell', state.runCommands[1])}

Pet preview route:

${codeBlock('text', state.petPreviewUrl)}

## Known Blockers

${bulletList(state.knownBlockers)}

## Next Tasks

${numberedList(state.nextTasks)}

## Important Decisions

${bulletList(state.importantDecisions)}

## Update Mechanism

This file is generated from \`docs/handoff-state.json\` plus stable package metadata. Git state is deliberately checked live at session start to avoid stale committed snapshots.

Use:

${codeBlock('powershell', 'npm run handoff:update')}

Optional local automation:

${codeBlock('powershell', 'npm run hooks:install')}

The installed git pre-commit hook runs \`npm run handoff:update\` and stages \`docs/next-session.md\` automatically before each commit.
`

writeFileSync(outputPath, content, 'utf8')
console.log(`Updated ${outputPath}`)
